CREATE TABLE public.perfiles (
  id uuid NOT NULL,
  nombre text NOT NULL,
  apellidos text,
  rol text DEFAULT 'Agente'::text,
  avatar_url text,
  telefono text,
  permisos jsonb DEFAULT '{"leads": true, "mensajes": true, "captaciones": true}'::jsonb,
  created_at timestamp with time zone DEFAULT now(),
  usuario text UNIQUE,
  onboarding_done boolean NOT NULL DEFAULT false,
  disponible boolean NOT NULL DEFAULT true,
  orden_reparto integer,
  zonas ARRAY NOT NULL DEFAULT '{}'::text[],
  especialidades ARRAY NOT NULL DEFAULT '{}'::text[],
  CONSTRAINT perfiles_pkey PRIMARY KEY (id),
  CONSTRAINT perfiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id)
);
