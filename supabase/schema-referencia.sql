CREATE TABLE public.mercado_inmuebles (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  idealista_id text NOT NULL UNIQUE,
  operacion text DEFAULT 'venta'::text,
  tipo text,
  codbarrio text,
  barrio text,
  lat double precision,
  lng double precision,
  precio numeric,
  metros numeric,
  precio_m2 numeric DEFAULT
CASE
    WHEN (metros > (0)::numeric) THEN round((precio / metros), 2)
    ELSE NULL::numeric
END,
  habitaciones integer,
  banos integer,
  planta text,
  ascensor boolean,
  estado_conservacion text,
  anunciante text,
  agencia_nombre text,
  activo boolean DEFAULT true,
  fecha_primera_vista timestamp with time zone DEFAULT now(),
  fecha_ultima_vista timestamp with time zone DEFAULT now(),
  fecha_baja timestamp with time zone,
  precio_baja numeric,
  raw jsonb,
  imagen_url text,
  usable_area numeric,
  exterior boolean,
  energia text,
  energia_kwh numeric,
  piscina boolean,
  jardin boolean,
  trastero boolean,
  parking boolean,
  terraza boolean,
  aire boolean,
  gastos_comunidad numeric,
  obra_nueva boolean,
  caracteristicas jsonb,
  tipo_detallado text,
  CONSTRAINT mercado_inmuebles_pkey PRIMARY KEY (id)
);
