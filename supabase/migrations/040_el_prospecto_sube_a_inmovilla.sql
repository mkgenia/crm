-- ============================================================================
-- 040 · El prospecto sube a Inmovilla
--
-- Al pasar una captación a prospecto, la ficha se crea también en Inmovilla por
-- su API REST. Esto guarda lo que hace falta para poder hacerlo y para saber
-- después qué pasó:
--
--   · `inmovilla_enums`: sus códigos. La operación, el tipo de inmueble, la
--     localidad y la zona no viajan por su nombre sino por un número suyo, y su
--     endpoint de enums sólo admite DOS peticiones por minuto —está puesto a
--     propósito para que nadie lo use como mapeo en vivo—. Así que se guardan.
--   · `inmovilla_ref_seq`: nuestra serie de referencias, MK00001 en adelante.
--     Serie propia y no la suya (`PR` + correlativo): si pidiéramos número de
--     la misma serie desde dos sitios, un día habría dos fichas con la misma
--     referencia. Y como la referencia es lo ÚNICO que identifica una ficha al
--     modificarla —su API actualiza por `ref`, y un alta con una referencia que
--     ya existe no da error, sino que pisa la ficha que la tenga—, eso no es un
--     susto: es perder una propiedad ajena.
--   · Tres columnas en `prospectos` para saber si subió, cuándo y con qué
--     fallo si no subió.
-- ============================================================================

-- 1) Sus códigos -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.inmovilla_enums (
  tipo    text    NOT NULL,
  valor   integer NOT NULL,
  nombre  text    NOT NULL,
  -- Para las zonas, la localidad a la que pertenecen: los nombres de barrio se
  -- repiten entre ciudades y sin esto "Centro" sería ambiguo.
  padre   integer,
  PRIMARY KEY (tipo, valor)
);

COMMENT ON TABLE public.inmovilla_enums IS
  'Los códigos de Inmovilla (keyacci, key_tipo, key_loca, key_zona). Se guardan porque su endpoint /enums/ admite 2 peticiones por minuto.';

CREATE INDEX IF NOT EXISTS inmovilla_enums_nombre_idx
  ON public.inmovilla_enums (tipo, lower(nombre));

ALTER TABLE public.inmovilla_enums ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.inmovilla_enums FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.inmovilla_enums TO service_role;

-- 2) Nuestra serie de referencias --------------------------------------------

CREATE SEQUENCE IF NOT EXISTS public.inmovilla_ref_seq START 1;
COMMENT ON SEQUENCE public.inmovilla_ref_seq IS
  'El correlativo de nuestras referencias en Inmovilla: MK00001, MK00002…';
GRANT USAGE, SELECT ON SEQUENCE public.inmovilla_ref_seq TO service_role;
-- La referencia se pide a la base y no se arma en Node: dos promociones a la
-- vez son dos peticiones distintas, y un contador leido-y-sumado desde fuera
-- les daria el mismo numero a las dos. nextval no tiene ese problema.
CREATE OR REPLACE FUNCTION public.siguiente_ref_inmovilla()
RETURNS text
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT 'MK' || lpad(nextval('public.inmovilla_ref_seq')::text, 5, '0');
$$;

REVOKE ALL ON FUNCTION public.siguiente_ref_inmovilla() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.siguiente_ref_inmovilla() TO service_role;


-- 3) Qué sabemos de cada prospecto en Inmovilla ------------------------------
--
-- La referencia ya tenía sitio: `propiedad_ref`, que nació para esto —el propio
-- mensaje de `promocionar_captacion` dice "cierra el prospecto con
-- propiedad_ref cuando el piso esté publicado"—. Se le suman el código interno
-- que devuelve el alta, cuándo subió y el último fallo.

ALTER TABLE public.prospectos
  ADD COLUMN IF NOT EXISTS inmovilla_cod_ofer  bigint,
  ADD COLUMN IF NOT EXISTS inmovilla_subido_en timestamptz,
  ADD COLUMN IF NOT EXISTS inmovilla_error     text;

COMMENT ON COLUMN public.prospectos.inmovilla_cod_ofer IS
  'El cod_ofer que devuelve el alta. Su documentación dice que no lo devuelve; sí lo hace.';
COMMENT ON COLUMN public.prospectos.inmovilla_error IS
  'El último fallo al intentar subirlo. Null = subió bien o no se ha intentado.';

